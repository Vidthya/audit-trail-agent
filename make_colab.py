"""Merge the package into one file for Google Colab:  python make_colab.py"""
import re

ORDER = ["synth", "rules", "llm", "extract", "matching", "trail", "review", "pipeline", "evaluate"]
HEADER = '''"""
Audit trail agent - single-file version for Google Colab.
Generated by make_colab.py from the audit_agent package (same code, merged).

Run the cells in order. Nothing here needs an API key except the optional
real-model cell at the bottom.
"""
import argparse
import datetime
import hashlib
import json
import os
import random
import re
'''
parts = [HEADER]
for name in ORDER:
    src = open(f"audit_agent/{name}.py").read()
    lines = []
    for line in src.splitlines():
        if re.match(r"(from \.\w+ import|import (argparse|datetime|hashlib|json|os|random|re)$)", line):
            continue
        lines.append(line)
    body = "\n".join(lines).strip()
    # drop module docstring, keep as a banner comment
    parts.append(f"\n\n# {'=' * 70}\n# {name}\n# {'=' * 70}\n{body}\n")
parts.append('''

# ======================================================================
# Run it
# ======================================================================
def build_extractor(kind):
    if kind == "rules":
        return RulesExtractor()
    if kind == "fake":
        return LLMExtractor(FakeLLM())
    if kind == "anthropic":
        return LLMExtractor(AnthropicLLM())
    raise ValueError(f"unknown extractor: {kind}")


def run_all(n=200, kinds=("rules", "fake"), out="outputs"):
    documents, bank_lines = make_dataset(n)
    rows = [evaluate(documents, bank_lines, build_extractor(k)) for k in kinds]
    print(format_report(rows))
    if "fake" in kinds:
        print("\\nNote: 'fake-llm' is a test stand-in, not a language model. "
              "Only 'anthropic' results say anything about a real model.")
    os.makedirs(out, exist_ok=True)
    trail, queue = EvidenceTrail(), ReviewQueue(["Auditor A", "Auditor B"])
    run_pipeline(documents, bank_lines, build_extractor(kinds[0]), trail, queue)
    trail.save(os.path.join(out, "evidence_trail.jsonl"))
    with open(os.path.join(out, "report.json"), "w") as handle:
        json.dump(rows, handle, indent=2)
    print(f"\\nSaved evidence trail ({len(trail.entries)} entries) and report to {out}/")
    return documents, bank_lines, trail, queue, rows


if __name__ == "__main__":
    run_all()
''')
open("audit_trail_agent_colab.py", "w").write("".join(parts))
