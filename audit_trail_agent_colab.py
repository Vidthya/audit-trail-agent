"""Turning an invoice's text into checked fields.

Every field must come with a quote from the document. The grounding check then
confirms the quote really is in the text and really says what the field says.
A value that fails is never accepted silently: the document goes to a person.
"""


FIELDS = ["supplier", "invoice_number", "invoice_date", "total"]

SYSTEM_PROMPT = (
    "You extract fields from one supplier invoice. Reply with JSON only, in this shape:\n"
    '{"supplier": {"value": "...", "quote": "..."}, "invoice_number": {"value": "...", "quote": "..."}, '
    '"invoice_date": {"value": "...", "quote": "..."}, "total": {"value": 0.00, "quote": "..."}}\n'
    "Rules: each quote must be copied exactly from the document. total is the amount payable, as a number. "
    "invoice_date is in the document's own format. If a field is not in the document, leave it out. "
    "Never guess."
)
PROMPT_HASH = hashlib.sha256(SYSTEM_PROMPT.encode()).hexdigest()[:12]


def squash(text):
    return re.sub(r"\s+", " ", text).strip()


def parse_date(text):
    """Read a date from text. Slashes are read in UK order (day/month/year)."""
    for pattern, fmt in ((r"\d{4}-\d{2}-\d{2}", "%Y-%m-%d"),
                         (r"\d{1,2} [A-Z][a-z]+ \d{4}", "%d %B %Y"),
                         (r"\d{2}/\d{2}/\d{4}", "%d/%m/%Y")):
        match = re.search(pattern, text)
        if match:
            try:
                return datetime.datetime.strptime(match.group(0), fmt).date()
            except ValueError:
                return None
    return None


def parse_amount(text):
    numbers = re.findall(r"[\d,]+\.\d{2}", text)
    if not numbers:
        return None
    return float(numbers[-1].replace(",", ""))


def check_field(field, value, quote, document_text):
    """Return None if the field is supported by the document, else a problem string."""
    if not isinstance(quote, str) or not quote.strip():
        return "no quote given"
    if squash(quote) not in squash(document_text):
        return "quote is not in the document"

    if field == "supplier":
        if not isinstance(value, str) or not value.strip():
            return "empty supplier"
        if squash(value) not in squash(quote):
            return "value is not in its quote"
    elif field == "invoice_number":
        if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z0-9\-/]{4,30}", value):
            return "invoice number has a bad format"
        if value not in quote:
            return "value is not in its quote"
    elif field == "invoice_date":
        parsed = parse_date(str(value))
        if parsed is None or not (2000 <= parsed.year <= 2100):
            return "date could not be read"
        if parse_date(quote) != parsed:
            return "date does not match its quote"
    elif field == "total":
        try:
            number = float(str(value).replace(",", ""))
        except ValueError:
            return "total is not a number"
        if not (0 < number < 10_000_000):
            return "total out of range"
        if parse_amount(quote) != round(number, 2):
            return "total does not match its quote"
    return None


class RulesExtractor:
    name = "rules-baseline"
    version = "1"

    def raw(self, text):
        return find_fields(text, tolerant=False)


class LLMExtractor:
    def __init__(self, llm):
        self.llm = llm
        self.name = getattr(llm, "name", "llm")
        self.version = getattr(llm, "version", "")

    def raw(self, text):
        reply = self.llm.complete(SYSTEM_PROMPT, f"<document>\n{text}\n</document>")
        start, end = reply.find("{"), reply.rfind("}")
        if start == -1 or end == -1:
            return {}
        try:
            data = json.loads(reply[start:end + 1])
        except json.JSONDecodeError:
            return {}
        return data if isinstance(data, dict) else {}


def extract_document(text, extractor):
    """Run an extractor, then check every field against the document.

    Returns {"fields", "quotes", "problems", "ok"}. fields holds only supported values."""
    raw = extractor.raw(text)
    fields, quotes, problems = {}, {}, []
    for field in FIELDS:
        item = raw.get(field)
        if not isinstance(item, dict):
            problems.append(f"{field}: missing")
            continue
        problem = check_field(field, item.get("value"), item.get("quote"), text)
        if problem:
            problems.append(f"{field}: {problem}")
            continue
        value = item["value"]
        if field == "invoice_date":
            value = parse_date(str(value)).isoformat()
        elif field == "total":
            value = round(float(str(value).replace(",", "")), 2)
        fields[field] = value
        quotes[field] = item["quote"]
    return {"fields": fields, "quotes": quotes, "problems": problems, "ok": not problems}


# ======================================================================
# matching
# ======================================================================
"""Matching invoices to bank payments.

This part is plain, predictable code on purpose: routine work is done by systems,
and anything unusual is flagged for a person to judge.
"""

WINDOW_DAYS = 60


def match_invoice(fields, bank_lines):
    """Compare one invoice with the bank lines. Returns (status, matched_line_ids).

    status is one of: ok, amount_mismatch, unpaid, duplicate_payment."""
    number = fields["invoice_number"]
    supplier = fields["supplier"].upper()
    total = fields["total"]
    invoice_date = datetime.date.fromisoformat(fields["invoice_date"])

    # First choice: the bank line quotes the invoice number.
    hits = [b for b in bank_lines if number in b["description"]]

    # Fallback: same supplier, same amount, paid within the window after the invoice.
    if not hits:
        for b in bank_lines:
            paid_on = datetime.date.fromisoformat(b["date"])
            if (supplier in b["description"] and round(abs(b["amount"]), 2) == total
                    and invoice_date <= paid_on <= invoice_date + datetime.timedelta(days=WINDOW_DAYS)):
                hits.append(b)

    ids = [b["line_id"] for b in hits]
    if not hits:
        return "unpaid", ids
    if len(hits) > 1:
        return "duplicate_payment", ids
    if round(abs(hits[0]["amount"]), 2) != total:
        return "amount_mismatch", ids
    return "ok", ids


