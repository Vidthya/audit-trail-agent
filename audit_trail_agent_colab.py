"""The language-model side, kept behind one small interface.

Anything with a complete(system, user) -> str method can be used. This lets the
tests and CI run with no API key, and a real model be plugged in for evaluation.
"""



class FakeLLM:
    """A stand-in for tests. It is NOT a language model and says nothing about
    how well a real one performs: it only lets us test the harness around it.

    hallucinate_every=k makes every k-th answer contain a made-up total with a
    made-up quote, to test that the grounding check catches it."""

    name = "fake-llm"
    version = "test"

    def __init__(self, hallucinate_every=0):
        self.hallucinate_every = hallucinate_every
        self.calls = 0

    def complete(self, system, user):
        self.calls += 1
        match = re.search(r"<document>\n(.*?)\n</document>", user, re.S)
        text = match.group(1) if match else ""
        raw = find_fields(text, tolerant=True)
        if self.hallucinate_every and self.calls % self.hallucinate_every == 0:
            raw["total"] = {"value": 999.99, "quote": "Total: GBP 999.99"}
        return json.dumps(raw)


class AnthropicLLM:
    """Real model through the Anthropic API. Needs `pip install anthropic` and an
    ANTHROPIC_API_KEY. Set ANTHROPIC_MODEL to choose a model.

    Note: written to the public API but not run against the live service while
    building this project, so run it on a small sample first."""

    def __init__(self, model=None):
        import anthropic  # imported here so the rest works without the package

        self.client = anthropic.Anthropic()
        self.model = model or os.environ.get("ANTHROPIC_MODEL", "claude-haiku-4-5-20251001")
        self.name = self.model
        self.version = "api"

    def complete(self, system, user):
        message = self.client.messages.create(
            model=self.model, max_tokens=600, temperature=0,
            system=system, messages=[{"role": "user", "content": user}])
        return message.content[0].text


