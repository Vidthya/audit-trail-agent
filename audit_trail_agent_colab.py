"""Synthetic invoices and bank lines, with known answers to test against.

All data is made up. No real client data is used anywhere in this project.
"""

SUPPLIERS = [
    "Acme Stationery Ltd", "Brightside Cleaning Services", "Calder Logistics Ltd",
    "Dunmore Office Supplies", "Elm Street Catering", "Fairview IT Solutions",
    "Greenleaf Print Co", "Hartwell Legal LLP", "Ironbridge Engineering Ltd",
    "Juniper Marketing Ltd", "Kestrel Couriers", "Lakeside Utilities Ltd",
    "Meridian Software Ltd", "Northgate Security Ltd", "Oakfield Training Ltd",
    "Pennine Packaging Ltd", "Quayside Travel Ltd", "Redwood Furniture Ltd",
    "Stonebridge Insurance Brokers", "Thames Valley Telecom",
]
DESCRIPTIONS = ["Consulting services", "Monthly subscription", "Office supplies",
                "Equipment hire", "Maintenance contract", "Printing and design"]

# What really happened to each invoice. "ok" means paid in full, once.
STATUSES = ["ok", "amount_mismatch", "unpaid", "duplicate_payment"]
STATUS_WEIGHTS = [0.82, 0.06, 0.08, 0.04]


def format_date(date, style):
    if style == 0:
        return date.strftime("%d %B %Y")      # 12 March 2024
    if style == 1:
        return date.strftime("%Y-%m-%d")      # 2024-03-12
    return date.strftime("%d/%m/%Y")          # 12/03/2024 (UK order)


def render_invoice(layout, supplier, number, date_text, net, vat, total, description):
    """Four layouts. Layout 3 is deliberately unusual, so a fixed-pattern
    reader fails on it and a flexible reader (such as an LLM) can succeed."""
    if layout == 0:
        return (f"{supplier}\n12 High Street, London\nINVOICE\nInvoice No: {number}\n"
                f"Date: {date_text}\nDescription: {description}\nNet: GBP {net:,.2f}\n"
                f"VAT (20%): GBP {vat:,.2f}\nTotal: GBP {total:,.2f}\nPayment terms: 30 days\n")
    if layout == 1:
        return (f"Tax Invoice\nFrom: {supplier}\nInvoice #{number}\nIssued {date_text}\n"
                f"{description}\nSubtotal £{net:,.2f}\nVAT £{vat:,.2f}\n"
                f"Amount Due: £{total:,.2f}\n")
    if layout == 2:
        return (f"{supplier}\nRef: {number}\nInvoice date {date_text}\n{description}\n"
                f"Net GBP {net:,.2f}\nVAT GBP {vat:,.2f}\nBalance due GBP {total:,.2f}\n")
    return (f"{supplier}\ninv. ref {number} dated {date_text}\n{description}\n"
            f"To pay: £{total:,.2f} incl. VAT\n")


def make_dataset(n=200, seed=7):
    """Return (documents, bank_lines).

    documents: list of dicts with doc_id, text and truth (the correct fields and status).
    bank_lines: list of dicts with line_id, date, description, amount (negative = money out).
    """
    rng = random.Random(seed)
    documents, bank_lines = [], []
    line_counter = 0

    for i in range(1, n + 1):
        supplier = rng.choice(SUPPLIERS)
        number = f"INV-2024-{i:04d}"
        date = datetime.date(2024, 1, 1) + datetime.timedelta(days=rng.randint(0, 330))
        net = round(rng.uniform(80, 9000), 2)
        vat = round(net * 0.2, 2)
        total = round(net + vat, 2)
        status = rng.choices(STATUSES, STATUS_WEIGHTS)[0]
        layout = rng.choices([0, 1, 2, 3], [0.3, 0.3, 0.25, 0.15])[0]
        style = rng.choice([0, 1, 2])

        text = render_invoice(layout, supplier, number, format_date(date, style),
                              net, vat, total, rng.choice(DESCRIPTIONS))
        documents.append({
            "doc_id": f"DOC-{i:04d}",
            "text": text,
            "truth": {"supplier": supplier, "invoice_number": number,
                      "invoice_date": date.isoformat(), "total": total,
                      "status": status, "layout": layout},
        })

        def add_line(paid, with_reference):
            nonlocal line_counter
            line_counter += 1
            paid_on = date + datetime.timedelta(days=rng.randint(10, 45))
            description = f"FASTER PAYMENT {supplier.upper()}"
            if with_reference:
                description += f" {number}"
            bank_lines.append({"line_id": f"BANK-{line_counter:05d}",
                               "date": paid_on.isoformat(),
                               "description": description, "amount": -paid})

        if status == "ok":
            add_line(total, with_reference=rng.random() < 0.8)
        elif status == "amount_mismatch":
            add_line(round(total * rng.choice([0.5, 0.9, 1.1, 1.5]), 2), True)
        elif status == "duplicate_payment":
            add_line(total, True)
            add_line(total, True)
        # "unpaid": no bank line at all

    bank_lines.sort(key=lambda b: (b["date"], b["line_id"]))
    return documents, bank_lines


