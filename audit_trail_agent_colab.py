# trail
# ======================================================================
"""The evidence trail.

Every step is written as one entry: what went in, where it came from, which model
and prompt produced the result, what came out, and who it is assigned to. Each entry
includes the hash of the one before, so any later edit breaks the chain and is
detected by verify().
"""


def sha256(value):
    if not isinstance(value, str):
        value = json.dumps(value, sort_keys=True, default=str)
    return hashlib.sha256(value.encode()).hexdigest()


class EvidenceTrail:
    def __init__(self):
        self.entries = []

    def append(self, step, doc_id, inputs, output, source=None, model=None, reviewer=None):
        entry = {
            "index": len(self.entries),
            "time": datetime.datetime.now(datetime.timezone.utc).isoformat(timespec="seconds"),
            "step": step,
            "doc_id": doc_id,
            "input_hash": sha256(inputs),
            "source": source,        # where the evidence lives, e.g. quotes from the document
            "model": model,          # which model and prompt produced the output
            "output": output,
            "reviewer": reviewer,    # the named person responsible
            "prev_hash": self.entries[-1]["hash"] if self.entries else "start",
        }
        entry["hash"] = sha256({k: v for k, v in entry.items() if k != "hash"})
        self.entries.append(entry)
        return entry

    def verify(self):
        """Return (True, None) if the chain is intact, else (False, index_of_first_bad_entry)."""
        previous = "start"
        for entry in self.entries:
            body = {k: v for k, v in entry.items() if k != "hash"}
            if entry["prev_hash"] != previous or entry["hash"] != sha256(body):
                return False, entry["index"]
            previous = entry["hash"]
        return True, None

    def for_document(self, doc_id):
        return [e for e in self.entries if e["doc_id"] == doc_id]

    def save(self, path):
        with open(path, "w") as handle:
            for entry in self.entries:
                handle.write(json.dumps(entry, sort_keys=True, default=str) + "\n")

    @classmethod
    def load(cls, path):
        trail = cls()
        with open(path) as handle:
            trail.entries = [json.loads(line) for line in handle if line.strip()]
        return trail


# ======================================================================
# review
# ======================================================================
"""Exceptions go to named auditors. The system never closes one by itself."""


class ReviewQueue:
    def __init__(self, reviewers):
        if not reviewers:
            raise ValueError("at least one named reviewer is required")
        self.reviewers = list(reviewers)
        self.items = {}     # doc_id -> {"reviewer", "reason", "decision", "note"}
        self._next = 0

    def assign(self, doc_id, reason):
        reviewer = self.reviewers[self._next % len(self.reviewers)]  # round robin
        self._next += 1
        self.items[doc_id] = {"reviewer": reviewer, "reason": reason, "decision": None, "note": ""}
        return reviewer

    def decide(self, trail, doc_id, reviewer, decision, note=""):
        """Record a reviewer's decision. Only the assigned reviewer may decide."""
        item = self.items.get(doc_id)
        if item is None:
            raise KeyError(f"{doc_id} is not in the review queue")
        if reviewer != item["reviewer"]:
            raise PermissionError(f"{doc_id} is assigned to {item['reviewer']}, not {reviewer}")
        if decision not in ("approved", "rejected"):
            raise ValueError("decision must be 'approved' or 'rejected'")
        item["decision"], item["note"] = decision, note
        trail.append("review_decision", doc_id, inputs={"reason": item["reason"]},
                     output={"decision": decision, "note": note}, reviewer=reviewer)

    def open_items(self):
        return {d: i for d, i in self.items.items() if i["decision"] is None}


# ======================================================================
# pipeline
# ======================================================================
"""The whole flow: extract, check, match, flag, and log every step."""


def run_pipeline(documents, bank_lines, extractor, trail, queue):
    """Process every document. Returns a list of one result dict per document."""
    model_id = f"{extractor.name}:{extractor.version}:prompt-{PROMPT_HASH}"
    results = []

    for doc in documents:
        doc_id = doc["doc_id"]
        extraction = extract_document(doc["text"], extractor)
        trail.append("extract", doc_id, inputs=doc["text"], model=model_id,
                     source={"quotes": extraction["quotes"]},
                     output={"fields": extraction["fields"], "problems": extraction["problems"]})

        if not extraction["ok"]:
            status, line_ids = "extraction_failed", []
            reviewer = queue.assign(doc_id, "; ".join(extraction["problems"]))
        else:
            status, line_ids = match_invoice(extraction["fields"], bank_lines)
            trail.append("match", doc_id, inputs=extraction["fields"],
                         source={"bank_lines": line_ids}, output={"status": status})
            reviewer = queue.assign(doc_id, status) if status != "ok" else None

        if reviewer:
            trail.append("assign", doc_id, inputs={"status": status},
                         output={"assigned_to": reviewer}, reviewer=reviewer)
        results.append({"doc_id": doc_id, "status": status, "fields": extraction["fields"],
                        "problems": extraction["problems"], "reviewer": reviewer})
    return results


# ======================================================================
# evaluate
# ======================================================================
"""Measuring an extractor against the known answers."""


def evaluate(documents, bank_lines, extractor, reviewers=("Auditor A", "Auditor B")):
    trail, queue = EvidenceTrail(), ReviewQueue(reviewers)
    results = run_pipeline(documents, bank_lines, extractor, trail, queue)

    n = len(documents)
    field_correct = {f: 0 for f in FIELDS}
    all_fields_correct = 0
    tp = fp = fn = tn = 0
    exact_status = 0

    for doc, result in zip(documents, results):
        truth = doc["truth"]
        right = 0
        for f in FIELDS:
            if result["fields"].get(f) == truth[f]:
                field_correct[f] += 1
                right += 1
        all_fields_correct += right == len(FIELDS)

        flagged = result["status"] != "ok"
        really_bad = truth["status"] != "ok"
        tp += flagged and really_bad
        fp += flagged and not really_bad
        fn += (not flagged) and really_bad
        tn += (not flagged) and not really_bad
        exact_status += result["status"] == truth["status"]

    ok_chain, _ = trail.verify()
    return {
        "extractor": extractor.name,
        "documents": n,
        "field_accuracy": {f: field_correct[f] / n for f in FIELDS},
        "all_fields_correct": all_fields_correct / n,
        "sent_to_review": len(queue.items),
        "exception_precision": tp / (tp + fp) if tp + fp else None,
        "exception_recall": tp / (tp + fn) if tp + fn else None,
        "exact_status": exact_status / n,
        "trail_entries": len(trail.entries),
        "trail_intact": ok_chain,
    }


def format_report(rows):
    def pct(x):
        return "n/a" if x is None else f"{100 * x:.1f}%"

    lines = ["Extractor".ljust(34) + "all fields  to review  exc.precision  exc.recall  status exact",
             "-" * 96]
    for r in rows:
        lines.append(r["extractor"].ljust(34) + pct(r["all_fields_correct"]).rjust(10)
                     + str(r["sent_to_review"]).rjust(11) + pct(r["exception_precision"]).rjust(14)
                     + pct(r["exception_recall"]).rjust(12) + pct(r["exact_status"]).rjust(14))
    return "\n".join(lines)


