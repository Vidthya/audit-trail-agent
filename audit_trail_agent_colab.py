"""A plain pattern-based reader: the baseline every language model must beat.

It works on the common invoice layouts and fails on unusual ones. That is
intended: a baseline shows what the model actually adds.
"""

NUMBER = r"[A-Z]{3}-\d{4}-\d{4}"
DATE = r"(?:\d{1,2} [A-Z][a-z]+ \d{4}|\d{4}-\d{2}-\d{2}|\d{2}/\d{2}/\d{4})"
AMOUNT = r"[\d,]+\.\d{2}"


def _grab(pattern, text):
    match = re.search(pattern, text)
    if not match:
        return None
    return {"value": match.group(1), "quote": match.group(0)}


def find_fields(text, tolerant=False):
    """Return {field: {"value", "quote"}} for the four fields we need.

    tolerant=False: common layouts only (the baseline).
    tolerant=True: also reads the unusual layout (used by the fake model)."""
    lines = text.splitlines()
    first = lines[0] if lines else ""
    from_line = _grab(r"From: (.+)", text)
    supplier = {"value": from_line["value"].strip(), "quote": from_line["quote"]} if from_line \
        else {"value": first.strip(), "quote": first.strip()}

    number_labels = r"(?:Invoice No:|Invoice #|Ref:)\s*"
    date_labels = r"(?:Date:|Issued|Invoice date)\s*"
    total_labels = r"(?:Total:|Amount Due:|Balance due)\s*(?:GBP|£)\s*"
    if tolerant:
        number_labels = r"(?:Invoice No:|Invoice #|Ref:|inv\. ref)\s*"
        date_labels = r"(?:Date:|Issued|Invoice date|dated)\s*"
        total_labels = r"(?:Total:|Amount Due:|Balance due|To pay:)\s*(?:GBP|£)\s*"

    number = _grab(f"{number_labels}({NUMBER})", text)
    date = _grab(f"{date_labels}({DATE})", text)
    total = _grab(f"{total_labels}({AMOUNT})", text)

    result = {"supplier": supplier, "invoice_number": number, "invoice_date": date, "total": total}
    return {key: value for key, value in result.items() if value}


